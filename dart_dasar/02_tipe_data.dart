void main() {
  // 1. Bilangan bulat (integer)
  int angkaBulat = 26;

  // 2. Bilangan desimal (floating point)
  double angkaDesimal = 3.14;

  // 3. Rangkaian karakter / teks (String)
  String nama = "M Fathan Ramdani";
  String pesan = "Halo, dunia mobile!";

  // 4. Nilai kebenaran (Boolean: true / false)
  bool sedangPraktikum = true;

  // 5. Dynamic / Type Inference dengan kata kunci 'var'
  var topik = "Dasar-Dasar Dart";

  print("=== Output Latihan Tipe Data ===");
  print("Angka Bulat      : $angkaBulat");
  print("Angka Desimal    : $angkaDesimal");
  print("Nama Mahasiswa   : $nama");
  print("Pesan Teks       : $pesan");
  print("Status Praktikum : $sedangPraktikum");
  print("Topik Pembahasan : $topik");
}
